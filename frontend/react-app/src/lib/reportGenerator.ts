// Main download report entry point
export async function downloadReport(essays: EssayData[], reportType: string, format: 'pdf' | 'docx') {
    if (!essays || essays.length === 0) return

    const primaryTitle = essays[0].title || essays[0].filename || 'Essay'
    const sanitizedTitle = primaryTitle.replace(/\.[^.]+$/, '').replace(/[^a-zA-Z0-9_-]/g, '_')
    const fileName = `IntelliScore_${reportType.toUpperCase()}_${sanitizedTitle}.${format}`

    if (format === 'docx') {
        // Native DOCX generation using `docx` library
        const docxBlob = await generateNativeDOCX(essays, reportType)
        triggerDirectFileDownload(docxBlob, fileName)
    } else {
        // High-Fidelity PDF Generation via jsPDF + html2canvas
        const htmlContent = await generateReportHTML(essays, reportType)
        const container = document.createElement('div')
        container.style.position = 'absolute'
        container.style.left = '-9999px'
        container.style.top = '0'
        container.style.width = '794px'
        container.style.backgroundColor = '#ffffff'
        container.style.opacity = '1'
        container.style.zIndex = '-9999'
        container.innerHTML = htmlContent

        document.body.appendChild(container)

        try {
            // Preload and wait for all nested chart images to be fully loaded/decoded
            const images = Array.from(container.querySelectorAll('img'))
            await Promise.all(
                images.map((img) => {
                    if (img.complete && img.naturalWidth !== 0) return Promise.resolve()
                    return new Promise((resolve) => {
                        img.onload = resolve
                        img.onerror = resolve
                        setTimeout(resolve, 500)
                    })
                })
            )
            await new Promise((resolve) => setTimeout(resolve, 150))

            const canvas = await html2canvas(container, {
                scale: 2,
                useCORS: true,
                backgroundColor: '#ffffff',
                logging: false,
                windowWidth: 794
            })
            document.body.removeChild(container)

            const imgData = canvas.toDataURL('image/jpeg', 0.98)
            const pdf = new jsPDF({
                orientation: 'portrait',
                unit: 'mm',
                format: 'a4'
            })

            const pdfWidth = pdf.internal.pageSize.getWidth()
            const pdfHeight = pdf.internal.pageSize.getHeight()
            const imgWidth = pdfWidth
            const imgHeight = (canvas.height * pdfWidth) / canvas.width

            let heightLeft = imgHeight
            let position = 0

            pdf.addImage(imgData, 'JPEG', 0, position, imgWidth, imgHeight)
            heightLeft -= pdfHeight

            while (heightLeft > 5) {
                position = heightLeft - imgHeight
                pdf.addPage()
                pdf.addImage(imgData, 'JPEG', 0, position, imgWidth, imgHeight)
                heightLeft -= pdfHeight
            }

            const pdfBlob = pdf.output('blob')
            triggerDirectFileDownload(pdfBlob, fileName)
        } catch (e) {
            console.error('jsPDF generation failed:', e)
            if (container.parentNode) document.body.removeChild(container)
        }
    }
}
