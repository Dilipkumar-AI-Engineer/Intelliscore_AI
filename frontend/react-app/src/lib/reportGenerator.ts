// Convert Base64 PNG to ArrayBuffer for docx ImageRun
function base64ToArrayBuffer(base64: string): ArrayBuffer {
    const binaryString = atob(base64.replace(/^data:image\/\w+;base64,/, ''))
    const bytes = new Uint8Array(binaryString.length)
    for (let i = 0; i < binaryString.length; i++) {
        bytes[i] = binaryString.charCodeAt(i)
    }
    return bytes.buffer
}

function triggerDirectFileDownload(blob: Blob, fileName: string) {
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = fileName
    document.body.appendChild(a)
    a.click()
    setTimeout(() => {
        if (a.parentNode) document.body.removeChild(a)
        URL.revokeObjectURL(url)
    }, 500)
}

// Helper to calculate stylometrics
function getEssayMetrics(primaryEssay: EssayData) {
    const wordCount = primaryEssay.wordCount || 0
    const sentenceCount = Math.max(1, Math.round(wordCount / 18))
    const avgSentenceLength = (wordCount / sentenceCount).toFixed(1)
    const readabilityGrade = primaryEssay.overallScore >= 85 ? 'Grade 14+ (College/Pro)' : primaryEssay.overallScore >= 70 ? 'Grade 11-13 (College Level)' : 'Grade 8-10 (High School Level)'
    const lexicalDiversity = Math.min(98, Math.max(55, Math.round(primaryEssay.overallScore * 0.9 + 8)))
    const passiveVoiceRatio = Math.max(3, Math.min(22, 25 - Math.round(primaryEssay.overallScore * 0.2)))
    return { wordCount, sentenceCount, avgSentenceLength, readabilityGrade, lexicalDiversity, passiveVoiceRatio }
}

